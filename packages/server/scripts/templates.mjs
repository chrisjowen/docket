// Builds the starter ontologies from docket's own default-sdlc.yaml: the SDLC
// template is that file as it is, and the lean catalogue and blank templates
// are cut from it, so all three move with docket. They are written into
// src/ontology/template-texts.ts as strings, so the built package needs no
// file reads or bundler loaders to offer them.
//
//   node scripts/templates.mjs          writes src/ontology/template-texts.ts
//   node scripts/templates.mjs --check  fails if it is out of date
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { isMap, isScalar, isSeq, parseDocument } from 'yaml'

const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, '..', 'src', 'ontology', 'template-texts.ts')

/** The types of the lean service catalogue: the most-used subset of SDLC. */
export const LEAN_TYPES = ['service', 'team', 'datasource', 'api', 'decision', 'constraint', 'environment']

/** docket's default ontology as its built package ships it. */
export function sdlcSource() {
  const docket = dirname(createRequire(import.meta.url).resolve('@chrisjowen/docket/package.json'))
  return readFileSync(join(docket, 'dist', 'ontology', 'default-sdlc.yaml'), 'utf8')
}

/** Keeps the lean types and every relationship whose ends still name one; `*` stays `*`. */
function lean(sdlc) {
  const doc = parseDocument(sdlc)
  doc.commentBefore = [
    " Lean service catalogue: the most-used part of docket's SDLC ontology -",
    ` ${LEAN_TYPES.join(', ')} - and the`,
    ' relationships between them, with the SDLC sources and their policies. Generated from',
    " docket's default-sdlc.yaml by docket-server (packages/server/scripts/templates.mjs)."
  ].join('\n')
  const types = doc.get('resourceTypes')
  for (const pair of [...types.items]) {
    if (!LEAN_TYPES.includes(String(pair.key.value ?? pair.key))) types.delete(pair.key)
  }
  const relationships = doc.get('relationships')
  for (const pair of [...relationships.items]) {
    const definition = pair.value
    let empty = false
    for (const end of ['from', 'to']) {
      const node = definition.get(end, true)
      if (isScalar(node) && node.value === '*') continue
      if (!isSeq(node)) continue
      node.items = node.items.filter((item) => LEAN_TYPES.includes(String(isScalar(item) ? item.value : item)))
      if (node.items.length === 0) empty = true
    }
    if (empty) relationships.delete(pair.key)
  }
  return strip(keepPolicies(doc)).toString()
}

/** No types and no relationships: only SDLC's evidence sources. */
function blank(sdlc) {
  const doc = parseDocument(sdlc)
  doc.commentBefore = [
    " Blank: no resource types or relationships yet, and docket's default sources",
    " and their policies. Generated from docket's default-sdlc.yaml by docket-server",
    ' (packages/server/scripts/templates.mjs).'
  ].join('\n')
  doc.set('resourceTypes', doc.createNode({}))
  doc.set('relationships', doc.createNode({}))
  return strip(keepPolicies(doc)).toString()
}

/** Drops the trust policies about a type or relationship the template no longer has. */
function keepPolicies(doc) {
  const kept = new Set([...(doc.get('resourceTypes')?.items ?? []), ...(doc.get('relationships')?.items ?? [])].map((pair) => String(pair.key.value ?? pair.key)))
  const policies = doc.getIn(['trust', 'policies'])
  if (isSeq(policies)) {
    policies.items = policies.items.filter((policy) => {
      const about = isMap(policy) ? policy.getIn(['when', 'about']) : undefined
      return about === undefined || kept.has(String(about))
    })
  }
  return doc
}

/** Drops the section banners that describe types the template no longer has. */
function strip(doc) {
  if (isMap(doc.contents)) {
    for (const pair of doc.contents.items) {
      const key = pair.key
      if (isScalar(key) && (key.value === 'resourceTypes' || key.value === 'relationships')) {
        key.commentBefore = undefined
        if (isMap(pair.value)) for (const item of pair.value.items) if (isScalar(item.key)) item.key.commentBefore = undefined
      }
    }
  }
  return doc
}

/** The three templates' YAML, by id. */
export function buildTemplates(sdlc = sdlcSource()) {
  return { sdlc, 'lean-catalogue': lean(sdlc), blank: blank(sdlc) }
}

/** A string as a template literal that reads back exactly as it is. */
const literal = (text) => `\`${text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')}\``

/** The module the templates are served from. */
export function templateModule(templates = buildTemplates()) {
  return [
    '// Generated by scripts/templates.mjs from docket\'s default-sdlc.yaml; do not edit.',
    '// Run `pnpm -C packages/server templates` after upgrading docket.',
    '',
    `export const SDLC_YAML = ${literal(templates.sdlc)}`,
    '',
    `export const LEAN_CATALOGUE_YAML = ${literal(templates['lean-catalogue'])}`,
    '',
    `export const BLANK_YAML = ${literal(templates.blank)}`,
    ''
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = templateModule()
  let current = null
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing: written below
  }
  if (current !== text) {
    if (process.argv.includes('--check')) {
      console.error('src/ontology/template-texts.ts is out of date: run node scripts/templates.mjs')
      process.exit(1)
    }
    writeFileSync(target, text)
    console.log('wrote src/ontology/template-texts.ts')
  }
}
